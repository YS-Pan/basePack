def _line(value: str) -> str:
    if any(character in value for character in ("\r", "\n", "\x00")) or "$(" in value:
        raise ValueError(f"Unsupported submit-field characters: {value!r}")
    return value


def arguments(values: list[str]) -> str:
    """Condor V2 syntax; only used for the small launcher argument list."""
    return '"' + " ".join("'" + _line(value).replace("'", "''").replace('"', '""') + "'"
                           for value in values) + '"'


def environment(values: dict[str, str]) -> str:
    """Condor environment V2 syntax, independent of Windows shell syntax."""
    for key in values:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise ValueError(f"Invalid environment variable name: {key!r}")
    return arguments([f"{key}={value}" for key, value in values.items()])


def path_field(value: str | Path) -> str:
    return _line(str(value).replace("\\", "/"))


def transfer_list(values: list[str]) -> str:
    if any("," in value for value in values):
        raise ValueError("Condor transfer paths cannot contain commas")
    return ",".join(path_field(value) for value in values)


def budget_config(machine) -> dict:
    budget = machine.raw["budget"]
    gpu = budget["total_gpu_mib"] - budget["embedding_gpu_mib"] - budget["system_gpu_mib"]
    if gpu < 0 or budget["cpus"] <= 0 or budget["memory_mib"] <= 0:
        raise ValueError(f"Invalid machine resource budget: {budget}")
    identity = hashlib.sha256(json.dumps(budget, sort_keys=True).encode()).hexdigest()[:16]
    text = "\n".join([
        "# Generated by basepack resources budget-config; edit the machine TOML source.",
        f'NUM_CPUS = {budget["cpus"]}', f'MEMORY = {budget["memory_mib"]}',
        f"BasePackGpuBudgetMiB = {gpu}", f'BasePackBudgetId = "{identity}"',
        "STARTD_ATTRS = $(STARTD_ATTRS), BasePackGpuBudgetMiB, BasePackBudgetId", "",
    ])
    return {"gpu_memory_mib": gpu, "budget_id": identity, "config": text}


@dataclass
class JobSpec:
    executable: str
    arguments: list[str] = field(default_factory=list)
    cwd: str = "."
    environment: dict[str, str] = field(default_factory=dict)
    cpus: int = 1
    memory_mib: int = 512
    disk_mib: int = 64
    gpu_memory_mib: int = 0
    queue_timeout: int = 300
    run_timeout: int = 600
    transfer_inputs: list[str] = field(default_factory=list)
    transfer_outputs: list[str] = field(default_factory=list)


class ResourceClient:
    def __init__(self, config):
        self.config = config
        self.machine = config.machine
        self.bin_dir = self.machine.path_value("htcondor", "bin_dir")
        self.env = dict(os.environ, CONDOR_CONFIG=str(self.machine.path_value("htcondor", "config_file")))
        self.encoding = locale.getencoding() if os.name == "nt" else "utf-8"

    def _call(self, command: str, *args, check=True, timeout=25):
        executable = self.bin_dir / (command + (".exe" if os.name == "nt" else ""))
        result = subprocess.run([str(executable), *map(str, args)], env=self.env,
                                capture_output=True, text=True, encoding=self.encoding,
                                timeout=timeout)
        if check and result.returncode:
            raise RuntimeError(f"{command} exited {result.returncode}\n{result.stdout}{result.stderr}")
        return result

    def _ads(self, command, *args):
        return json.loads(self._call(command, *args, "-json").stdout)

    def _ad(self, job_id):
        if not re.fullmatch(r"\d+\.\d+", job_id):
            raise ValueError(f"Expected cluster.proc job ID: {job_id!r}")
        queue = self._ads("condor_q", job_id)
        if queue:
            return queue[0], False
        history = self._ads("condor_history", job_id, "-limit", "1")
        if not history:
            raise LookupError(f"Job {job_id} is absent from queue and history")
        return history[0], True

    def _admission(self, spec):
        budget = self.machine.raw["budget"]
        for key in ("cpus", "memory_mib", "disk_mib", "queue_timeout", "run_timeout"):
            if getattr(spec, key) <= 0:
                raise ValueError(f"{key} must be positive")
        for key in ("cpus", "memory_mib"):
            if getattr(spec, key) > budget[key]:
                raise ValueError(f"Job {key}={getattr(spec,key)} exceeds machine budget {budget[key]}")
        cwd = Path(spec.cwd)
        if shutil.disk_usage(cwd).free < spec.disk_mib * 1024**2:
            raise ValueError(f"Insufficient project output disk space at {cwd}")
        published = budget_config(self.machine)
        if spec.gpu_memory_mib < 0 or spec.gpu_memory_mib > published["gpu_memory_mib"]:
            raise ValueError(f"GPU peak {spec.gpu_memory_mib} MiB exceeds ordinary job budget {published['gpu_memory_mib']} MiB")
        slots = self._ads("condor_status", "-constraint", "PartitionableSlot =?= true")
        matching = [slot for slot in slots if slot.get("Machine", "").lower() == socket.gethostname().lower()]
        if not matching or any(slot.get("BasePackBudgetId") != published["budget_id"] or
                               slot.get("BasePackGpuBudgetMiB") != published["gpu_memory_mib"] or
                               slot.get("TotalCpus") != budget["cpus"] or
                               slot.get("TotalMemory") != budget["memory_mib"]
                               for slot in matching):
            raise ValueError("Condor has not published this machine budget; install resources budget-config and reconfigure")
        return published

    def submit(self, spec: JobSpec) -> dict:
        cwd = (self.config.root / spec.cwd).resolve()
        spec.cwd = str(cwd)
        if not Path(spec.executable).is_absolute():
            raise ValueError("Job executable must be an explicit absolute path")
        published = self._admission(spec)
        token = uuid.uuid4().hex
        folder = self.config.jobs_dir / token
        folder.mkdir(parents=True)
        transfer = bool(spec.transfer_inputs or spec.transfer_outputs)
        payload = folder / "basepack-job.json"
        receipt = folder / "worker.json"
        metadata = {"submission_id": token, "spec": asdict(spec), "worker_receipt": str(receipt)}
        payload.write_text(json.dumps(metadata | {"executable": spec.executable, "arguments": spec.arguments},
                                      ensure_ascii=False, indent=2), encoding="utf-8")
        env = {"OMP_NUM_THREADS": str(spec.cpus), "MKL_NUM_THREADS": str(spec.cpus),
               "OPENBLAS_NUM_THREADS": str(spec.cpus), "NUMEXPR_NUM_THREADS": str(spec.cpus),
               **spec.environment}
        if any(key.upper() == "CUDA_VISIBLE_DEVICES" for key in env):
            raise ValueError("CUDA_VISIBLE_DEVICES belongs to Condor's device allocation")
        requirement = (f'TARGET.Machine == {json.dumps(socket.gethostname())}'
                       f' && TARGET.BasePackBudgetId == "{published["budget_id"]}"')
        if spec.gpu_memory_mib:
            requirement += f' && TARGET.BasePackGpuBudgetMiB >= {spec.gpu_memory_mib}'
        lines = [
            "universe = vanilla", f"executable = {path_field(self.config.python)}",
            "transfer_executable = False", "getenv = False",
            "arguments = " + arguments(["-I", "-m", "basepack.resources.worker", payload.name if transfer else str(payload)]),
            f"environment = {environment(env)}", f"initialdir = {path_field(cwd)}",
            f"output = {path_field(folder/'stdout.txt')}", f"error = {path_field(folder/'stderr.txt')}",
            f"log = {path_field(folder/'events.log')}", f"request_cpus = {spec.cpus}",
            f"request_memory = {spec.memory_mib} MB", f"request_disk = {spec.disk_mib} MB",
            f"request_gpus = {int(bool(spec.gpu_memory_mib))}", f"requirements = {requirement}",
            f'+BasePackSubmissionId = "{token}"', f'+BasePackPayload = {json.dumps(payload.as_posix(), ensure_ascii=False)}',
            f"+BasePackQueueTimeout = {spec.queue_timeout}", f"+BasePackRunTimeout = {spec.run_timeout}",
            f"allowed_execute_duration = {spec.run_timeout}",
            "periodic_remove = "
            f"(JobStatus == 1 && time() - QDate >= {spec.queue_timeout}) || "
            f"(JobStatus == 2 && JobCurrentStartExecutingDate > 0 && time() - JobCurrentStartExecutingDate >= {spec.run_timeout}) || "
            "(JobStatus == 5 && member(HoldReasonCode, {46,47}))",
            "notification = Never", "on_exit_remove = True",
            f"should_transfer_files = {'YES' if transfer else 'NO'}",
        ]
        if transfer:
            inputs = [str(payload), *[str((cwd / path).resolve()) for path in spec.transfer_inputs]]
            for output in spec.transfer_outputs:
                if Path(output).is_absolute() or ".." in Path(output).parts:
                    raise ValueError(f"Transfer output must be relative to scratch: {output}")
            lines.extend(["when_to_transfer_output = ON_EXIT", "transfer_input_files = " + transfer_list(inputs),
                          "transfer_output_files = " + transfer_list(spec.transfer_outputs)])
        submit = folder / "job.sub"
        submit.write_text("\n".join([*lines, "queue 1", ""]), encoding=self.encoding)
        try:
            result = self._call("condor_submit", "-terse", submit)
        except (RuntimeError, subprocess.TimeoutExpired) as error:
            # A lost submit response does not authorize another submission.
            matches = self._ads("condor_q", "-constraint", f'BasePackSubmissionId == "{token}"')
            if not matches:
                matches = self._ads("condor_history", "-constraint", f'BasePackSubmissionId == "{token}"', "-limit", "1")
            if not matches:
                raise
            ad = matches[0]
            job_id = f'{ad["ClusterId"]}.{ad["ProcId"]}'
            metadata["submit_response_error"] = str(error)
            if isinstance(error, subprocess.TimeoutExpired):
                metadata["submit_response_error"] += f"\nstdout: {error.stdout!r}\nstderr: {error.stderr!r}"
        else:
            job_id = re.search(r"\d+\.\d+", result.stdout).group()
        submitted = {"job_id": job_id, "submission_id": token, "job_dir": str(folder), "payload": str(payload)}
        if "submit_response_error" in metadata:
            submitted["submit_response_error"] = metadata["submit_response_error"]
        (folder / "submission.json").write_text(json.dumps(submitted, indent=2), encoding="utf-8")
        self._call("condor_reschedule")
        return submitted

    def status(self, job_id: str, *, analyze=False) -> dict:
        ad, history = self._ad(job_id)
        number = ad["JobStatus"]
        state = {1: "queued", 2: "running", 3: "removed", 4: "completed", 5: "held", 6: "transferring", 7: "suspended"}[number]
        finished = _terminal_time(ad, self.encoding) if history else None
        started = ad.get("JobCurrentStartExecutingDate")
        end = finished if history else time.time()
        result = {
            "job_id": job_id, "state": state, "terminal": history,
            "exit_code": ad.get("ExitCode"), "exit_signal": ad.get("ExitSignal"),
            "reason": ad.get("HoldReason") or ad.get("RemoveReason"),
            "submitted": ad["QDate"], "started": started,
            "finished": finished, "remote_host": ad.get("RemoteHost", ad.get("LastRemoteHost")),
            "elapsed_seconds": max(0, end - ad["QDate"]) if end is not None else None,
            "queued_seconds": max(0, (started or end) - ad["QDate"]) if started or end is not None else None,
            "running_seconds": max(0, end - started) if started and end is not None else (None if started else 0),
            "stdout": ad.get("Out"), "stderr": ad.get("Err"), "event_log": ad.get("UserLog"),
        }
        if history and number == 4:
            payload = json.loads(Path(ad["BasePackPayload"]).read_text(encoding="utf-8"))
            missing = [str(Path(payload["spec"]["cwd"]) / output) for output in payload["spec"]["transfer_outputs"]
                       if not (Path(payload["spec"]["cwd"]) / output).exists()]
            result.update(success=ad.get("ExitCode") == 0 and not ad.get("ExitBySignal", False) and not missing,
                          missing_outputs=missing)
        elif history:
            result["success"] = False
            if (ad.get("HoldReasonCode") in (46, 47) or
                    "periodicremove" in (ad.get("RemoveReason") or "").lower().replace("_", "")):
                result["timeout"] = "execution" if ad.get("JobCurrentStartExecutingDate") else "queue"
        if analyze and number == 1:
            diagnostic = self._call("condor_q", job_id, "-better-analyze", check=False)
            result["analysis"] = diagnostic.stdout + diagnostic.stderr
        return result

    def _cleanup(self, job_id: str, timeout=30, expected_pids=()) -> dict:
        deadline = time.monotonic() + timeout
        while True:
            ad, history = self._ad(job_id)
            payload_path = ad.get("BasePackPayload")
            if payload_path:
                payload = json.loads(Path(payload_path).read_text(encoding="utf-8"))
                receipt = Path(payload["worker_receipt"])
                if receipt.exists():
                    worker = json.loads(receipt.read_text(encoding="utf-8"))
                    expected_pids = set(expected_pids) | {worker[key] for key in ("pid", "child_pid")}
            try:
                processes = _process_parents()
                worker_gone = not (set(expected_pids) & processes.keys())
            except OSError as error:
                return {"cleanup_confirmed": False, "cleanup_error": str(error)}
            # Condor owns all descendants; a completed history record plus gone launcher/application
            # confirms the process family was reaped, not merely that condor_rm was accepted.
            if history and worker_gone:
                return {"cleanup_confirmed": True, "cleanup_scope": "known_processes_and_condor_history",
                        "checked_pids": sorted(expected_pids)}
            if time.monotonic() >= deadline:
                return {"cleanup_confirmed": False, "cleanup_error": "Queue/history or local worker still active at cleanup deadline"}
            time.sleep(1)

    def cancel(self, job_id: str, *, cleanup_timeout=30) -> dict:
        ad, history = self._ad(job_id)
        expected_pids = set()
        if "BasePackPayload" in ad:
            payload = json.loads(Path(ad["BasePackPayload"]).read_text(encoding="utf-8"))
            receipt = Path(payload["worker_receipt"])
            if receipt.exists():
                worker = json.loads(receipt.read_text(encoding="utf-8"))
                expected_pids = _descendants({worker["pid"], worker["child_pid"]}, _process_parents())
        if not history:
            result = self._call("condor_rm", job_id, check=False)
            if result.returncode:
                return self.status(job_id) | {"cleanup_confirmed": False, "cleanup_error": result.stdout + result.stderr}
        cleanup = self._cleanup(job_id, cleanup_timeout, expected_pids)
        return self.status(job_id) | cleanup

    def wait(self, job_id: str, *, timeout=300, enforce_limits=False) -> dict:
        deadline = time.monotonic() + timeout
        while True:
            result = self.status(job_id)
            if result["terminal"]:
                return result | self._cleanup(job_id)
            if result["state"] == "held":
                if enforce_limits:
                    cleanup = self.cancel(job_id)
                    if "execution time" in (result["reason"] or "").lower():
                        result["timeout"] = "execution"
                    return cleanup | {"original_state": "held", "reason": result["reason"],
                                      **({"timeout": result["timeout"]} if "timeout" in result else {})}
                return result
            if enforce_limits:
                ad, _ = self._ad(job_id)
                started = ad.get("JobCurrentStartExecutingDate")
                if started and time.time() - started >= ad["BasePackRunTimeout"]:
                    return self.cancel(job_id) | {"timeout": "execution"}
                if not started and time.time() - ad["QDate"] >= ad["BasePackQueueTimeout"]:
                    return self.cancel(job_id) | {"timeout": "queue"}
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return result | {"observation_expired": True}
            wait_start = time.monotonic()
            self._call("condor_wait", "-wait", max(1, min(5, math.ceil(remaining))), result["event_log"], job_id,
                       check=False, timeout=min(7, max(2, remaining + 1)))
            if time.monotonic() - wait_start < 0.1:
                time.sleep(min(1, remaining))

    def run(self, spec: JobSpec) -> dict:
        submitted = self.submit(spec)
        result = self.wait(submitted["job_id"], timeout=spec.queue_timeout + spec.run_timeout + 30, enforce_limits=True)
        if result.get("observation_expired"):
            result = self.cancel(submitted["job_id"]) | {"timeout": "overall"}
        return submitted | result


def _descendants(roots: set[int], parents: dict[int, int]) -> set[int]:
    found = set(roots)
    while True:
        children = {pid for pid, parent in parents.items() if parent in found}
        if children <= found:
            return found
        found.update(children)


def _terminal_time(ad: dict, encoding: str) -> int | None:
    if ad.get("CompletionDate"):
        return ad["CompletionDate"]
    # Removed jobs can retain QDate as EnteredCurrentStatus. The native abort event
    # records the removal time; process-family cleanup is confirmed separately.
    log = Path(ad["UserLog"])
    if not log.exists():
        return None
    timestamp = None
    for match in re.finditer(r"^(?:005|009) \((\d+)\.(\d+)\.\d+\) (\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)",
                             log.read_text(encoding=encoding), re.MULTILINE):
        if (int(match[1]), int(match[2])) == (ad["ClusterId"], ad["ProcId"]):
            timestamp = int(datetime.fromisoformat(match[3]).timestamp())
    return timestamp


def _process_parents() -> dict[int, int]:
    """Toolhelp lists PIDs and parent PIDs without opening another user's process."""
    if os.name != "nt":
        import psutil
        return {process.pid: process.ppid() for process in psutil.process_iter()}
    import ctypes
    from ctypes import wintypes

    class ProcessEntry(ctypes.Structure):
        _fields_ = [("dwSize", wintypes.DWORD), ("cntUsage", wintypes.DWORD),
                    ("th32ProcessID", wintypes.DWORD), ("th32DefaultHeapID", ctypes.c_size_t),
                    ("th32ModuleID", wintypes.DWORD), ("cntThreads", wintypes.DWORD),
                    ("th32ParentProcessID", wintypes.DWORD), ("pcPriClassBase", wintypes.LONG),
                    ("dwFlags", wintypes.DWORD), ("szExeFile", wintypes.WCHAR * 260)]

    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.CreateToolhelp32Snapshot.argtypes = [wintypes.DWORD, wintypes.DWORD]
    kernel.CreateToolhelp32Snapshot.restype = wintypes.HANDLE
    for name in ("Process32FirstW", "Process32NextW"):
        function = getattr(kernel, name)
        function.argtypes = [wintypes.HANDLE, ctypes.POINTER(ProcessEntry)]
        function.restype = wintypes.BOOL
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    snapshot = kernel.CreateToolhelp32Snapshot(2, 0)
    if snapshot == wintypes.HANDLE(-1).value:
        raise ctypes.WinError(ctypes.get_last_error())
    parents = {}
    entry = ProcessEntry(dwSize=ctypes.sizeof(ProcessEntry))
    try:
        more = kernel.Process32FirstW(snapshot, ctypes.byref(entry))
        while more:
            parents[entry.th32ProcessID] = entry.th32ParentProcessID
            more = kernel.Process32NextW(snapshot, ctypes.byref(entry))
        if ctypes.get_last_error() != 18:
            raise ctypes.WinError(ctypes.get_last_error())
    finally:
        kernel.CloseHandle(snapshot)
    return parents
